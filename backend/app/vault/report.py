# A Unicode font so Devanagari / Kannada script and symbols render; Helvetica only covers Latin-1.
_UNICODE_FONTS = [
    "/System/Library/Fonts/Supplemental/Arial Unicode.ttf",
    "/Library/Fonts/Arial Unicode.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "C:/Windows/Fonts/arialuni.ttf",
]
TEXT_FONT, _GLYPHS = "Helvetica", None
for _path in _UNICODE_FONTS:
    if Path(_path).exists():
        try:
            _font = TTFont("KavachUnicode", _path)
            pdfmetrics.registerFont(_font)
            TEXT_FONT, _GLYPHS = "KavachUnicode", set(_font.face.charToGlyph)
            break
        except Exception:
            continue


def pdf_text(value) -> str:
    """Escape for ReportLab markup and replace characters the font can't draw (e.g. emoji)
    with their code point, so nothing silently turns into a blank box."""
    out = []
    for ch in str(value or ""):
        cp = ord(ch)
        drawable = cp < 256 if _GLYPHS is None else (cp in _GLYPHS or ch in "\n\t")
        out.append(ch if drawable else f"[U+{cp:04X}]")
    return escape("".join(out))


_ss = getSampleStyleSheet()
