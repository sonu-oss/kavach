def ist(ts: str) -> str:
    return datetime.fromisoformat(ts).astimezone(IST).strftime("%d/%m/%Y %H:%M:%S IST")


def p(text: str, style: str = "body") -> Paragraph:
    return Paragraph(text, S[style])


def build_report() -> bytes:
    rows = store.all_rows()
    result = store.verify(rows)
    status = {r["id"]: r["status"] for r in result["records"]}
    generated = datetime.now(timezone.utc).isoformat()

    captures: "OrderedDict[str, list[dict]]" = OrderedDict()
    for r in rows:
        captures.setdefault(r["capture_id"], []).append(r)

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
        title="Kavach AI evidence report", author="Kavach AI",
    )
    story = []

    # ---------- cover + summary ----------
    story += [
        p("Electronic Evidence Report", "title"),
        p(f"Generated by Kavach AI on {ist(generated)} · Report ID {result['head_hash'][:12] if rows else 'EMPTY'}", "sub"),
        Spacer(1, 8),
    ]

    analyses = [json.loads(c[0]["analysis_json"]) for c in captures.values() if c[0]["analysis_json"]]
    messages = [r for r in rows if r["kind"] == "message"]
    shots = [r for r in rows if r["kind"] == "screenshot"]
    categories = sorted({CATEGORY_LABEL.get(a.get("category"), a.get("category")) for a in analyses})
    max_risk = max((a.get("risk_score", 0) for a in analyses), default=None)
    span = f"{ist(rows[0]['server_timestamp'])} to {ist(rows[-1]['server_timestamp'])}" if rows else "n/a"

    summary = [
        ["Conversations captured", str(len(captures))],
        ["Platforms", ", ".join(sorted({r["platform"] for r in rows})) or "n/a"],
        ["Records sealed", f"{len(rows)} ({len(messages)} messages, {len(shots)} screenshots)"],
        ["Flagged messages", str(sum(1 for r in messages if r["flagged"]))],
        ["Threats detected (AI)", ", ".join(categories) or "n/a"],
        ["Highest risk score", f"{max_risk}/100" if max_risk is not None else "n/a"],
        ["Capture period (server time)", span],
    ]
    story.append(p("1. Case summary", "h2"))
    story.append(_kv_table(summary))

    # ---------- verification ----------
    story.append(p("2. Integrity verification", "h2"))
    if not rows:
        story.append(p("The vault is empty."))
    elif result["ok"]:
        story.append(_banner(
            f"<b>CHAIN VERIFIED.</b> All {result['count']} records match their SHA-256 seals and every link "
            f"to the previous record is intact. Checked at {ist(result['checked_at'])}.", GREEN))
    else:
        bad = [r for r in result["records"] if r["status"] not in ("ok", "after_break")]
        story.append(_banner(
            f"<b>CHAIN BROKEN at record #{result['first_broken_id']}.</b> "
            f"{len(bad)} record(s) failed verification; records after the break cannot be relied on. "
            f"Checked at {ist(result['checked_at'])}.", RED))
    if rows:
        story += [
            Spacer(1, 6),
            p("Chain head (fingerprint of the entire vault):", "small"),
            p(result["head_hash"], "mono"),
            Spacer(1, 4),
            p("Each record's seal is <font name='Courier'>SHA-256(canonical JSON of {record fields, "
              "server_timestamp, prev_hash})</font>. The timestamp is set by the Kavach server, not the "
              "phone. Changing any message, timestamp or screenshot, or reordering records, changes the "
              "seal and breaks every later link. See Annex A to re-check independently.", "small"),
        ]

    # ---------- per capture ----------
    story.append(p("3. Evidence items", "h2"))
    for n, (cid, items) in enumerate(captures.items(), 1):
        first = items[0]
        a = json.loads(first["analysis_json"]) if first["analysis_json"] else None
        head = [
            p(f"3.{n} {pdf_text(first['conversation'])} · {pdf_text(first['platform'])}", "h3"),
            p(f"Saved {ist(first['server_timestamp'])} · capture {cid}"
              + (f" · source {escape(first['url'])}" if first["url"] else ""), "small"),
        ]
        if a:
            head.append(Spacer(1, 3))
            head.append(_kv_table([
                ["AI assessment", f"{CATEGORY_LABEL.get(a.get('category'), a.get('category'))} · "
                                  f"risk {a.get('risk_score')}/100 ({a.get('severity')})"],
                ["Reason", a.get("reason", "")],
            ]))
        story.append(KeepTogether(head))
        story.append(Spacer(1, 4))

        for s in (r for r in items if r["kind"] == "screenshot"):
            path = store.screenshot_path(s["screenshot_sha256"])
            label = "Chat capture" if s["screenshot_kind"] == "chat_capture" else "Original screenshot"
            block = [p(f"#{s['id']} {label} · {_status_label(status[s['id']])}", "small")]
            image = _fit_image(path, max_w=90 * mm, max_h=120 * mm) if path else None
            block.append(image or p("<font color='#dc2f45'>Screenshot file missing or unreadable.</font>", "small"))
            block.append(p(f"SHA-256 {s['hash']}", "mono"))
            story.append(KeepTogether(block))
            story.append(Spacer(1, 6))

        table = [[p("#", "head"), p("Time", "head"), p("Sender", "head"),
                  p("Message", "head"), p("SHA-256 seal", "head")]]
        style = [
            ("GRID", (0, 0), (-1, -1), 0.4, LINE),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f4f3f8")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]
        for i, r in enumerate((r for r in items if r["kind"] == "message"), 1):
            st = status[r["id"]]
            flag = " <font name='Helvetica-Bold' color='#dc2f45'>[flagged]</font>" if r["flagged"] else ""
            mark = "" if st == "ok" else f"<br/><font name='Helvetica-Bold' color='#dc2f45'>{_status_label(st)}</font>"
            table.append([
                p(str(r["id"]), "cell"),
                p(pdf_text(r["message_time"]), "cell"),
                p(pdf_text(r["sender"]), "cell"),
                p(pdf_text(r["message_text"]) + flag + mark, "cell"),
                p(r["hash"], "mono"),
            ])
            if st != "ok":
                style.append(("BACKGROUND", (0, i), (-1, i), colors.HexColor("#fde8eb")))
        t = Table(table, colWidths=[9 * mm, 13 * mm, 24 * mm, 76 * mm, 56 * mm], repeatRows=1)
        t.setStyle(TableStyle(style))
        story += [t, Spacer(1, 10)]

    # ---------- annex: how to verify ----------
    story.append(p("Annex A. How to verify this report independently", "h2"))
    story.append(p(
        "Export the vault records (id order). For each record build the JSON object "
        "<font name='Courier'>{\"record\": {id, capture_id, kind, platform, conversation, url, sender, "
        "message_text, message_time, message_ref, flagged, screenshot_kind, screenshot_sha256, "
        "analysis_json, client_captured_at}, \"server_timestamp\": ..., \"prev_hash\": ...}</font>, "
        "serialise it with sorted keys and no whitespace (UTF-8), and compute SHA-256. The result must "
        "equal the record's seal, and each record's prev_hash must equal the previous record's seal "
        f"(the first record uses {store.GENESIS[:8]}…, sixty-four zeros). Screenshot files must hash to "
        "their recorded screenshot_sha256. Characters the PDF font cannot display (such as emoji) are "
        "printed as [U+XXXX]; the stored records and hashes use the original characters."))

    # ---------- Section 63 BSA certificate ----------
    story += [PageBreak()] + _certificate(result)

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()


# ---------- pieces ----------

def _kv_table(rows: list[list[str]]) -> Table:
    data = [[p(escape(k), "head"), p(pdf_text(v), "cell")] for k, v in rows]
    t = Table(data, colWidths=[48 * mm, 130 * mm])
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, LINE),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f8f7fc")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return t


def _banner(html: str, color) -> Table:
    t = Table([[Paragraph(html, ParagraphStyle("bn", parent=S["body"], textColor=colors.white))]],
              colWidths=[178 * mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), color),
        ("LEFTPADDING", (0, 0), (-1, -1), 8), ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    return t


def _fit_image(path, max_w, max_h) -> Image | None:
    try:
        img = Image(str(path))
        img.imageWidth  # forces the file to be read now, not mid-build
    except Exception:
        return None
    ratio = min(max_w / img.imageWidth, max_h / img.imageHeight)
    img.drawWidth, img.drawHeight = img.imageWidth * ratio, img.imageHeight * ratio
    img.hAlign = "LEFT"
    return img


def _status_label(status: str) -> str:
    return {
        "ok": "verified",
        "tampered": "ALTERED: content no longer matches its seal",
        "rehashed": "ALTERED: edited and re-sealed; next link broken",
        "broken_link": "LINK BROKEN: previous record was altered",
        "file_changed": "SCREENSHOT FILE CHANGED OR MISSING",
        "after_break": "unverified (after chain break)",
    }.get(status, status)


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(16 * mm, 9 * mm, "Kavach AI · Electronic evidence report · Not legal advice")
    canvas.drawRightString(A4[0] - 16 * mm, 9 * mm, f"Page {doc.page}")
    canvas.restoreState()


